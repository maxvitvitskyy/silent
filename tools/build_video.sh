#!/bin/bash
# Ролики для галереї: вихідні .mov з телефона -> веб-оптимізований MP4 + постер.
#
# Вихідні файли — 1080x1920, ~15 Мбіт/с, без звукової доріжки взагалі.
# Для сайту це надлишок: у лайтбоксі вертикальне відео впирається у висоту
# екрана, тож на екрані 900px заввишки воно займає ~430px завширшки — навіть з
# урахуванням подвійної щільності це 860px. Звідси ширина 864.
#
# CRF 28 обрано заміром, а не на око: SSIM проти оригіналу 0.989 (26 дає 0.991
# при +40% ваги, 30 — 0.987). Вага падає з 42 МБ до 5.
#
# Звук: у вихідних .mov доріжка AAC стерео 48 кГц стоїть НУЛЬОВИМ потоком, а
#   відео — першим. Через це поверхнева перевірка легко показує «звуку немає».
#   Тому потоки мапимо явно: -map 0:v:0 -map 0:a:0. У файлі є ще mjpeg-мініатюра
#   й службовий data-потік — без явного мапінгу вони теж можуть потрапити в
#   контейнер.
# -movflags +faststart: заголовок на початок файлу, інакше браузер чекає
#   завантаження всього файлу перед першим кадром.
# -pix_fmt yuv420p: без цього Safari не програє.
set -e
cd "$(dirname "$0")/.."
mkdir -p video/web images/vid
n=0
for f in video/*.mov; do
  n=$((n+1))
  out="video/web/silent-$n.mp4"
  poster="images/vid/silent-$n-poster.jpg"
  echo "[$n] $f"
  ffmpeg -v error -y -i "$f" -map 0:v:0 -map 0:a:0 \
    -c:v libx264 -preset slow -crf 28 -vf "scale=864:-2" -pix_fmt yuv420p \
    -c:a aac -b:a 128k -ac 2 \
    -movflags +faststart "$out"
  # Кадр для постера: не з нульової секунди — там часто ще змазано рухом.
  dur=$(ffprobe -v error -show_entries format=duration -of csv=p=0 "$f")
  ts=$(echo "$dur" | awk '{printf "%.2f", ($1>4)?2.0:$1/2}')
  ffmpeg -v error -y -ss "$ts" -i "$f" -frames:v 1 -q:v 2 "$poster"
  printf "    -> %s (%s), постер з %ss\n" "$out" "$(du -h "$out" | cut -f1)" "$ts"
done
echo "готово: $n роликів"
